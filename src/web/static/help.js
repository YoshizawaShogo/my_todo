"use strict";
// ヘルプタブ。操作の説明と、MCP・Jira の設定方法。

let helpAbout = null;

function render_help() {
  if (!helpAbout) {
    api("GET", "/about").then((a) => { helpAbout = a; render_help(); });
    return;
  }
  const exe = helpAbout.exe_path || "my_todo";
  const db = helpAbout.db_path;
  // 空白を含むパスは引用符で囲む
  const quote_arg = (s) => (/\s/.test(s) ? JSON.stringify(s) : s);
  const code = (text) => {
    const pre = el("pre", { class: "help_code" }, el("code", {}, text));
    const copy = el("button", { type: "button", class: "small_button copy", onclick: () => {
      navigator.clipboard?.writeText(text).then(() => toast("コピーしました"), () => toast("コピーできませんでした", "error"));
    } }, "コピー");
    return el("div", { class: "help_code_box" }, pre, copy);
  };
  const h = (text) => el("h3", {}, text);
  const p = (...kids) => el("p", {}, ...kids);
  const ul = (...items) => el("ul", {}, ...items.map((i) => el("li", {}, ...[].concat(i))));
  const kbd = (k) => el("kbd", {}, k);

  const sections = [
    el("h2", {}, "ヘルプ"),

    h("ふだんの流れ"),
    ul(
      ["思いついたことは ", kbd("/"), " で「未分類」に書き留める"],
      "整理するときに、未分類の行を線表へドラッグし、右側を横にドラッグして日程を決める",
      "1 日の終わりに「工数記録」タブで、その日の勤務時間をタスクの割合で振り分ける",
      "週に 1 回など、「Jira」タブで工数を Jira に送る",
    ),

    h("線表"),
    ul(
      "時間軸の上でホイールを回すと、表示範囲が 1 日ずつ前後に動く（名前欄の上では行が上下にスクロール）。「前の週」「次の週」「今日」でも移動できる",
      "名前をドラッグして並べ替え・階層を変える。行の上端・下端に落とすと前後に、中央に落とすと子になる。左上の「タスク」に落とすと最上位の末尾へ",
      "名前をダブルクリックで名前を変更。チェックで完了",
      "日付のない行は、右側を横にドラッグすると開始予定日〜終了予定日が決まる",
      "バーの中央をドラッグで移動、両端をドラッグで期間を増減",
      "バーの色：薄い青＝未着手、青＝作業中、緑＝完了（予定の期間、なければ着手〜完了）、赤枠＝終了予定日を過ぎた未完了",
      "◆＝終了予定日だけのタスク、▶＝次の予定、横に倒した I＝子タスクの範囲",
      "絞り込みのタグは、親に付けたタグが子にも効く",
    ),

    h("詳細"),
    ul(
      "過去も未来も、完了したものも含めて全タスクを表で出す。見出しをクリックで並べ替え",
      "プリセット（今日やること・今週・期限切れなど）か、状態・日付・タグ・場所の条件で絞り込む。選んでいる範囲をもう一度押すと「指定なし」に戻る",
      "「条件を保存」で名前を付けて残せる",
    ),

    h("工数記録"),
    ul(
      "その日の勤務時間（残業込みの実際の時間）を入れ、タスクごとの割合をスライダーで決める",
      "勤務時間を 0.5 時間刻みで振り分け、合計は必ず勤務時間に一致する。10 時間働いた日は 1.25D になる（1D の時間は設定で変えられる）",
      "記録した工数は「詳細」タブの「実績」列や、右の詳細パネルで確認できる",
    ),

    h("キーボード"),
    ul(
      [kbd("/"), " 未分類に追加"],
      [kbd("Ctrl"), "+", kbd("Z"), " 元に戻す　", kbd("Ctrl"), "+", kbd("Y"), " やり直し（追加・変更・移動・削除・工数・設定。AI からの変更も戻せる）"],
      [kbd("Esc"), " 詳細パネルを閉じる・入力をやめる"],
      "日付の欄は 11/25、2026-11-25、今日、明日、+3（3 日後）のように文字でも入れられる",
    ),

    h("AI から使う（MCP）"),
    p("MCP は、AI のアプリ（Claude Code や Claude Desktop など）が、外のアプリの機能を呼び出すための共通の仕組みです。",
      "このアプリは MCP サーバーとして動けるので、AI に「今日やることは？」「〇〇を ToDo に足して」「今日は 10 時間、A に 7 割、B に 3 割で工数をつけて」と頼めます。"),
    p("このアプリ側ですることはありません。AI のアプリ側に、次のように一度だけ登録してください（AI のアプリがこの .exe を必要なときに起動します。画面を開いていなくても使え、データは同じファイルを共有します）。"),
    el("h4", {}, "Claude Code の場合"),
    code(`claude mcp add my_todo -- ${quote_arg(exe)} mcp --db ${quote_arg(db)}`),
    el("h4", {}, "Claude Desktop などの設定ファイル（mcpServers）の場合"),
    code(JSON.stringify({ mcpServers: { my_todo: { command: exe, args: ["mcp", "--db", db] } } }, null, 2)),
    p("使えるツール：今日・今週の予定（get_schedule）、タスクの一覧・詳細、ToDo の追加、更新・移動・削除、その日の工数の確認と記録、タグの一覧、元に戻す・やり直し。"),

    h("Jira 連携"),
    ul(
      "社内サーバー版（Data Center / Server）の Jira に、PAT（個人用アクセストークン）で接続する",
      "PAT は Jira の右上のプロフィール →「個人用アクセストークン（Personal Access Tokens）」→「トークンを作成」で発行する（会社で発行が許されているか確認すること）",
      "PAT は OS の資格情報（Windows の資格情報マネージャー）に保存し、データベースには保存しない。環境変数 MY_TODO_JIRA_TOKEN があればそちらを使う",
      "右の詳細パネルの「Jira 課題」に課題キー（ABC-123）を入れて紐付ける。子タスクの工数は、紐付けた一番近い親の課題にまとめて送る",
      "送る前に、日ごと・課題ごとの内容（新規・更新・削除）を確認できる。送った後に工数を変えたら、もう一度送れば Jira 側も直る",
    ),

    h("データ"),
    ul(
      ["データの場所：", el("code", {}, db)],
      "バックアップは、アプリを止めてからこのファイルをコピーする（動かしたままなら、同じ場所の -wal ファイルも一緒に）",
      `バージョン ${helpAbout.version}`,
    ),
  ];
  $("help_body").replaceChildren(...sections);
}
